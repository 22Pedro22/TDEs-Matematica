"""#Justificativa das exclusões
A coluna Channel foi removida de X porque é um rótulo (tipo de cliente: Horeca ou Varejo); o K-means não pode usar a resposta. Ela será guardada apenas para comparar com os grupos depois do agrupamento. A coluna Region foi excluída por ser categórica nominal: os valores 1, 2 e 3 são apenas códigos, e ela descreve onde o cliente está, não como ele compra. O agrupamento usa somente os seis atributos de gasto.
"""

# Criando o padronizador

scaler = StandardScaler()

# Aplicando a padronização
X_scaled = scaler.fit_transform(X)

