X_scaled = pd.DataFrame(
    X_scaled,
    columns=colunas
)

# Visualizando os dados
X_scaled.head()

print(X_scaled.mean().round(6)); print(X_scaled.std(ddof=0).round(6))

"""Explicação da padronização
A padronização é necessária porque os atributos possuem escalas diferentes. O StandardScaler transforma os valores utilizando a média e o desvio padrão de cada coluna.

Onde:
- x representa o valor original.
- μ representa a média.
- σ representa o desvio padrão.
- z representa o valor padronizado.
"""

# Comparando os valores originais e padronizados

comparacao = pd.DataFrame({
    "Valor original": X["Fresh"],
    "Valor padronizado": X_scaled["Fresh"]
})

comparacao.head(10)

"""A comparação demonstra que os valores originais foram transformados pela padronização. Após esse processo, os dados passaram a ter média próxima de zero e desvio padrão próximo de um. Isso permite que os seis atributos tenham influência mais equilibrada no cálculo das distâncias realizado pelo K-means.

### Etapa 3 — Execução do algoritmo K-means

Nesta etapa, será aplicado o algoritmo K-means utilizando os dados padronizados anteriormente.

Serão testados valores de K entre 1 e 10, representando diferentes quantidades de grupos. Para melhorar a qualidade dos resultados, será utilizada a inicialização `k-means++`, com 10 inicializações para cada valor de K.

O objetivo é observar como os dados são agrupados e registrar o valor de inércia (J) de cada execução.
"""

# Lista para guardar os resultados
resultados_kmeans = []

# Testar valores de K de 1 até 10
for k in range(1, 11):

    modelo = KMeans(
        n_clusters=k,
        init="k-means++",
        n_init=20,
        random_state=42
    )

    # Treinar o modelo
    modelo.fit(X_scaled)

    # Guardar o valor de inércia
    resultados_kmeans.append({
        "K": k,
        "Inercia (J)": modelo.inertia_
    })

# Mostrar os resultados
tabela_kmeans = pd.DataFrame(resultados_kmeans)

tabela_kmeans

"""### Análise inicial dos resultados

Após executar o algoritmo K-means para valores de K entre 1 e 10, observou-se que a inércia diminuiu progressivamente conforme aumentou a quantidade de grupos.

Esse comportamento é esperado, pois uma quantidade maior de grupos permite que os clientes sejam distribuídos em conjuntos menores e mais próximos de seus respectivos centroides.

Entretanto, a menor inércia não significa necessariamente o melhor agrupamento. Por isso, serão utilizados também o método do cotovelo e o coeficiente de silhueta para auxiliar na escolha do número adequado de grupos.
"""

plt.figure(figsize=(8, 5))

plt.plot(
    tabela_kmeans["K"],
    tabela_kmeans["Inercia (J)"],
    marker="o"
)

plt.title("Método do Cotovelo - K-means")
plt.xlabel("Quantidade de grupos (K)")
plt.ylabel("Inércia (J)")
plt.xticks(range(1, 11))
plt.grid(True)

plt.show()

"""### Análise do coeficiente de silhueta (Silhouette Score)

Nesta etapa, será calculado o coeficiente de silhueta para valores de K entre 2 e 10.

Esse indicador avalia a qualidade dos agrupamentos, considerando a proximidade dos clientes dentro do próprio grupo e a distância em relação aos outros grupos.

Quanto mais próximo de 1 for o resultado, melhor tende a ser a separação entre os grupos.
"""

# Lista para armazenar os resultados
resultados_silhouette = []

# Testar K de 2 até 10
for k in range(2, 11):

    modelo = KMeans(
        n_clusters=k,
        init="k-means++",
        n_init=20,
        random_state=42
    )

    # Treinar o modelo
    labels = modelo.fit_predict(X_scaled)

    # Calcular o Silhouette Score
    score = silhouette_score(X_scaled, labels)

    resultados_silhouette.append({
        "K": k,
        "Silhouette Score": score
    })

# Mostrar tabela
tabela_silhouette = pd.DataFrame(resultados_silhouette)

tabela_silhouette

plt.figure(figsize=(8, 5))

plt.plot(
    tabela_silhouette["K"],
    tabela_silhouette["Silhouette Score"],
    marker="o"
)

plt.title("Silhouette Score por quantidade de grupos")
plt.xlabel("Quantidade de grupos (K)")
plt.ylabel("Silhouette Score")
plt.xticks(range(2, 11))
plt.grid(True)

plt.show()

"""### Análise dos gráficos de silhueta

Serão construídos gráficos de silhueta para K=2 e K=3, permitindo visualizar a distribuição dos clientes em cada grupo.

Essa análise ajuda a identificar a qualidade da separação, a distribuição dos clientes e possíveis observações que não se encaixam bem nos agrupamentos.
"""

from sklearn.metrics import silhouette_samples

# Analisar K=2 e K=3
for k in [2, 3]:

    modelo = KMeans(
        n_clusters=k,
        init="k-means++",
        n_init=20,
        random_state=42
    )

    labels = modelo.fit_predict(X_scaled)

    # Calcular silhueta individual
    valores_silhueta = silhouette_samples(X_scaled, labels)

    plt.figure(figsize=(8, 5))

    y_inicio = 10

    for i in range(k):

        valores_grupo = valores_silhueta[labels == i]
        valores_grupo.sort()

        tamanho = len(valores_grupo)
        y_fim = y_inicio + tamanho

        plt.fill_betweenx(
            np.arange(y_inicio, y_fim),
            0,
            valores_grupo
        )

        plt.text(-0.05, y_inicio + tamanho / 2, f"Grupo {i}")

        y_inicio = y_fim + 10

    plt.axvline(
        x=silhouette_score(X_scaled, labels),
        linestyle="--",
        label="Média da silhueta"
    )

    plt.title(f"Gráfico de Silhueta - K={k}")
    plt.xlabel("Coeficiente de Silhueta")
    plt.ylabel("Clientes agrupados")
    plt.legend()
    plt.show()

for k in [2, 3]:
    modelo = KMeans(n_clusters=k, init="k-means++", n_init=20, random_state=42)
    lab = modelo.fit_predict(X_scaled)
    s = silhouette_samples(X_scaled, lab)
    print(f"\nk={k} | J = {modelo.inertia_:.2f} | silhueta média = {s.mean():.3f} | pontos com s<0: {(s<0).sum()}")
    for g in range(k):
        print(f"  grupo {g}: n = {(lab==g).sum():3d} | silhueta média = {s[lab==g].mean():.2f}")

"""### Escolha da quantidade de grupos (K)

No método do cotovelo, a inércia vai caindo aos poucos, de 2640 (k=1) até 606 (k=10), e não dá pra ver um “cotovelo” claro. Só dá pra ver que a maior queda é entre k=1, 2 e 3.

Na silhueta, o maior valor foi com k=2 (0,614). Com k=3 deu 0,548, e de k=4 pra frente ficou entre 0,31 e 0,38. Então escolhi k=2.

Olhando o gráfico da silhueta, dá pra ver que o resultado não é tão bom quanto o número sugere. O grupo grande (404 clientes) está bem agrupado, mas o grupo pequeno (36 clientes) tem silhueta perto de 0 e 19 pontos negativos, ou seja, alguns clientes estão mal encaixados. Com k=3 apareceu um grupo com só 2 clientes, que não serve como grupo. Por isso k=2 foi a melhor opção, mas com essa ressalva.

### 5. Interpretação dos Grupos

Nesta etapa, vamos analisar as características de consumo dos dois grupos (clusters) encontrados para $K=2$.

Para isso, primeiro obteremos as etiquetas de cada cliente e a posição dos centroides. Em seguida, despadronizaremos os centroides para que voltem à escala monetária original (m.u./ano), permitindo uma interpretação direta dos gastos médios por categoria de produto.
"""

# Treinando o modelo final com K=2
modelo_final = KMeans(n_clusters=2, init='k-means++', n_init=20, random_state=42)
labels_final = modelo_final.fit_predict(X_scaled)

# Obtendo o tamanho de cada grupo
tamanho_grupo_0 = (labels_final == 0).sum()
tamanho_grupo_1 = (labels_final == 1).sum()

# Obtendo os centroides no espaço padronizado
centroides_scaled = modelo_final.cluster_centers_

# Desfazendo a padronização para voltar às unidades originais (m.u./ano)
centroides_originais = scaler.inverse_transform(centroides_scaled)

# Criando o DataFrame comparativo dos centroides
tabela_centroides = pd.DataFrame(
    centroides_originais,
    columns=colunas,
    index=['Centroide Grupo 0', 'Centroide Grupo 1']
)

# Adicionando o tamanho de cada grupo à tabela
tabela_centroides['Tamanho do Grupo (|C_k|)'] = [tamanho_grupo_0, tamanho_grupo_1]

# Exibindo os resultados
display(tabela_centroides.round(2))

"""#### Descrição e Perfis dos Grupos Gerados

Analisando a tabela de centroides nas unidades originais de gasto, podemos definir e nomear os dois grupos de clientes identificados:

* **Grupo 0 — Clientes de Alto Gasto / Atacadistas de Grande Porte (n = 36):**
  Este grupo representa uma pequena parcela de clientes ($8,18\%$ do total) que apresenta uma média de gastos extremamente alta em quase todas as categorias, especialmente em **Laticínios (Milk)**, **Mercearia (Grocery)** e **Detergentes/Papel**. São possivelmente distribuidores regionais, supermercados de rede ou grandes redes de hotéis e restaurantes com alto volume de compra.
  
* **Grupo 1 — Clientes de Gasto Moderado / Pequenos Comércios Locais (n = 404):**
  Este grupo abrange a grande maioria dos clientes ($91,82\%$ do total). O perfil de consumo é focado em gastos mais modestos e controlados. O principal destaque de consumo deles está em produtos **Frescos (Fresh)**, mantendo gastos muito baixos nas outras categorias. São caracterizados como pequenos restaurantes, padarias, hotéis familiares ou mercearias locais de bairro.

#### Visualização Gráfica em 2D dos Grupos

Como a matriz $X$ possui 6 dimensões, vamos escolher dois atributos de alto impacto para projetar e visualizar os clusters em um gráfico de dispersão de 2 dimensões. Usaremos os atributos `Grocery` (Mercearia) e `Fresh` (Frescos), plotados na escala de valores originais para facilitar a visualização do comportamento real dos clientes.
"""

plt.figure(figsize=(10, 6))

# Plotando os pontos e colorindo pelos clusters identificados
sns.scatterplot(
    x=X['Fresh'],
    y=X['Grocery'],
    hue=labels_final,
    palette='Set1',
    s=70,
    alpha=0.8
)

# Plotando os centroides originais
plt.scatter(
    centroides_originais[:, 0], # Fresh é o índice 0
    centroides_originais[:, 2], # Grocery é o índice 2
    color='black',
    marker='X',
    s=250,
    label='Centroides'
)

plt.title('Dispersão 2D dos Clusters: Gastos com Frescos vs Mercearia', fontsize=14)
plt.xlabel('Gasto Anual com Produtos Frescos (m.u./ano)', fontsize=12)
plt.ylabel('Gasto Anual com Mercearia (m.u./ano)', fontsize=12)
plt.legend(title='Grupo')
plt.grid(True, linestyle='--', alpha=0.5)
plt.show()

"""### 6. Avaliação Crítica

Nesta última seção, avaliaremos a robustez do agrupamento por meio do cruzamento com o canal de vendas real e discutiremos as principais limitações do algoritmo aplicadas a este conjunto de dados.

#### Comparação com o Rótulo Real (`Channel`)

A coluna original `Channel` (que indica 1 = Horeca — Hotéis/Restaurantes/Cafés; 2 = Varejo) foi retirada antes de rodarmos o K-means para que o algoritmo agrupar de forma puramente não supervisionada.

Vamos agora criar uma matriz de confusão (cruzamento) para analisar se o K-means conseguiu reencontrar naturalmente esses canais originais através dos gastos.
"""

# Criando um DataFrame comparativo
comparativo_canais = pd.DataFrame({
    'Canal Real (Channel)': df['Channel'].map({1: '1 - Horeca', 2: '2 - Varejo'}),
    'Cluster K-means': labels_final
})

# Gerando tabela de contingência (matriz de cruzamento)
tabela_cruzamento = pd.crosstab(
    comparativo_canais['Canal Real (Channel)'],
    comparativo_canais['Cluster K-means']
)

display(tabela_cruzamento)

"""**Análise do Cruzamento:**

A comparação entre os grupos encontrados pelo K-means e os canais originais de venda demonstra que existe uma relação entre os padrões de consumo e o canal comercial, mas essa relação não é perfeita.

O Grupo 0 é composto predominantemente por clientes do Varejo, totalizando 33 clientes desse canal e apenas 3 clientes Horeca. Portanto, aproximadamente 91,67% desse grupo pertence ao Varejo.

Já o Grupo 1 contém 295 clientes Horeca e 109 clientes do Varejo. Isso demonstra que o agrupamento reuniu a maior parte dos clientes dos dois canais em um mesmo grupo de menor gasto relativo.

Esses resultados indicam que o K-means identificou principalmente diferenças nos volumes e padrões de gastos, mas não conseguiu separar completamente os clientes de acordo com seus canais comerciais originais.

#### Discussão de Limitações do Modelo

Apesar de termos encontrado um agrupamento coerente sob a ótica das métricas gerais, o modelo K-means apresenta limitações claras neste conjunto de dados:

1. **Sensibilidade a Outliers:**
   O dataset do Wholesale Customers é extremamente assimétrico e possui outliers de altíssimo valor (clientes que gastam muito acima da média). Como o K-means tenta minimizar a soma dos erros quadráticos (Inércia), esses poucos clientes puxam os centroides intensamente para si. Isso ficou claro na análise de $K=3$ gerando um grupo com apenas 2 clientes (outliers gigantes), reduzindo a utilidade prática de criar um terceiro perfil comercial.
   
2. **Suposição de Grupos Esféricos:**
   O K-means trabalha calculando a distância euclidiana, o que pressupõe que os agrupamentos possuem formato esférico de densidades e volumes semelhantes. No gráfico de dispersão gerado, nota-se que o Grupo 1 tem uma distribuição alongada e muito mais densa, enquanto o Grupo 0 é esparso e espalhado, violando a premissa de simetria geométrica ideal do algoritmo, justificando a presença de pontos com silhueta negativa.
"""

